"""Command line: `staledetect check`, `staledetect ask`, `staledetect doctor`."""

from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import date

from . import prompts
from .bifrost_client import BifrostClient, GatewayError
from .config import Settings
from .http import request_json
from .pipeline import Options, run
from .report import to_html, to_markdown
from .tavily_client import TavilyClient


def _write_outputs(result: dict, out_dir: str) -> None:
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "report.json"), "w", encoding="utf-8") as fh:
        json.dump(result, fh, indent=2, ensure_ascii=False)
    with open(os.path.join(out_dir, "report.md"), "w", encoding="utf-8") as fh:
        fh.write(to_markdown(result))
    with open(os.path.join(out_dir, "report.html"), "w", encoding="utf-8") as fh:
        fh.write(to_html(result))


def _print_summary(result: dict) -> None:
    s = result["summary"]
    print(f"\n{s['claims_found']} claims, {s['claims_checked']} re-checked: "
          f"{s['supported']} supported, {s['changed']} changed, {s['unverifiable']} unverifiable")
    for c in result["claims"]:
        if c.get("status") in {"checked", "error"}:
            r = c["result"]
            extra = f"  -> now: {r['current_fact']}" if r.get("current_fact") else ""
            print(f"  {r['verdict'].upper():<12} {r['indicator']['confidence']:.2f}  {c['text'][:90]}{extra}")
    calls = result["gateway"]["llm_calls"]
    if calls["fallback_calls"]:
        print(f"WARNING: primary model unavailable for {calls['fallback_calls']} call(s); Bifrost fell back to "
              f"{', '.join(calls['served_by'])}")
    print(f"Bifrost: {calls['calls']} calls, {calls['fallback_calls']} via fallback; "
          f"Tavily: {result['research']['tavily_searches']} searches")
    b = result["gateway"].get("bifrost")
    if b:
        print(f"Bifrost logged cost: ${b.get('logged_cost_usd', 0):.6f}")


def cmd_check(args: argparse.Namespace, answer: str | None = None) -> int:
    settings = Settings()
    if answer is None:
        if args.answer_file == "-":
            answer = sys.stdin.read()
        else:
            with open(args.answer_file, encoding="utf-8") as fh:
                answer = fh.read()
    llm = BifrostClient(settings, simulate_outage=args.simulate_outage)
    tavily = TavilyClient(settings, use_cache=not args.no_cache)
    opts = Options(max_claims=args.max_claims, rewrite=args.rewrite,
                   today=date.fromisoformat(args.as_of) if args.as_of else date.today())
    try:
        result = run(answer, llm=llm, tavily=tavily, question=args.question, opts=opts,
                     log=lambda m: print(m, file=sys.stderr))
    except GatewayError as exc:
        print(f"Stopped: {exc}", file=sys.stderr)
        return 2
    _write_outputs(result, args.out)
    _print_summary(result)
    print(f"Reports written to {args.out}/report.(md|html|json)")
    return 0


def cmd_ask(args: argparse.Namespace) -> int:
    """Generate an answer with a (deliberately older) model through Bifrost, then check it."""
    settings = Settings()
    llm = BifrostClient(settings)
    try:
        answer = llm.chat([{"role": "system", "content": prompts.ASK_SYSTEM},
                           {"role": "user", "content": args.question}], purpose="answer",
                          model=args.answer_model, fallbacks=[], max_tokens=700, temperature=0.2)
    except GatewayError as exc:
        print(f"Stopped: {exc}", file=sys.stderr)
        return 2
    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "answer.md"), "w", encoding="utf-8") as fh:
        fh.write(f"<!-- generated by {args.answer_model} via Bifrost -->\n{answer}\n")
    print(f"--- answer from {args.answer_model} ---\n{answer}\n---", file=sys.stderr)
    args.question = args.question
    return cmd_check(args, answer=answer)


def cmd_doctor(_args: argparse.Namespace) -> int:
    settings = Settings()
    ok = True
    try:
        body, _, _ = request_json("GET", f"{settings.bifrost_url.rstrip('/')}/health", timeout=10)
        print(f"Bifrost gateway at {settings.bifrost_url}: {body.get('status', body)}")
    except Exception as exc:  # noqa: BLE001
        ok = False
        print(f"Bifrost gateway at {settings.bifrost_url}: NOT reachable ({exc})")
    if ok:
        try:
            BifrostClient(settings).chat([{"role": "user", "content": "Reply with the word ok."}], purpose="doctor",
                                         max_tokens=5)
            print(f"Virtual key + model {settings.model}: ok")
        except GatewayError as exc:
            ok = False
            print(f"Virtual key + model: FAILED ({exc})")
    usage = TavilyClient(settings).usage()
    if usage:
        print(f"Tavily: plan {usage['plan']}, {usage['used']}/{usage['limit']} credits used")
    else:
        ok = False
        print("Tavily: key missing or invalid (set TAVILY_API_KEY)")
    return 0 if ok else 1


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="staledetect", description="Find and re-check stale claims in an LLM answer.")
    sub = p.add_subparsers(dest="cmd", required=True)

    def common(sp: argparse.ArgumentParser) -> None:
        sp.add_argument("--out", default="runs/latest", help="output folder for report.md/html/json")
        sp.add_argument("--max-claims", type=int, default=8, help="max claims to re-check live (default 8)")
        sp.add_argument("--rewrite", action="store_true", help="also produce a corrected answer with citations")
        sp.add_argument("--simulate-outage", action="store_true",
                        help="route the primary model to a dead upstream so Bifrost's fallback takes over")
        sp.add_argument("--no-cache", action="store_true", help="ignore cached Tavily results")
        sp.add_argument("--as-of", help="treat this date (YYYY-MM-DD) as today")

    c = sub.add_parser("check", help="check an existing answer")
    c.add_argument("answer_file", help="file with the LLM answer, or - for stdin")
    c.add_argument("--question", help="the question the answer responds to (optional, improves extraction)")
    common(c)
    c.set_defaults(func=cmd_check)

    a = sub.add_parser("ask", help="ask a model a question through Bifrost, then check its answer")
    a.add_argument("question")
    a.add_argument("--answer-model", default="otari/meta/llama-3.1-8b-instruct",
                   help="model that writes the answer (an older model makes stale answers likely)")
    common(a)
    a.set_defaults(func=cmd_ask)

    d = sub.add_parser("doctor", help="check Bifrost and Tavily connectivity")
    d.set_defaults(func=cmd_doctor)
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
